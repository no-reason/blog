% (1) 求非齐次方程组的特解
A1 = [2 9 0; 3 4 11; 2 2 6];
b1 = [13; 6; 6];
x1 = A1 \ b1;
disp('(1) 非齐次方程组的特解:');
disp(x1);

% (2) 求欠定方程组的最小范数解
A2 = [2 4 7 4; 9 3 5 6];
b2 = [8; 5];
x2 = pinv(A2) * b2;
disp('(2) 欠定方程组的最小范数解:');
disp(x2);

% (3) 求方程组的通解
A3 = [1 -3 -1 1; 3 -1 -3 4; 1 5 -9 -8];
b3 = [1; 4; 6];

% 1. 求方程组的一个特解
x_particular = pinv(A3) * b3;

% 2. 求对应齐次方程组的基础解系 ('r' 参数表示求有理基)
x_null = null(A3, 'r');

disp('(3) 方程组的一个特解为:');
disp(x_particular);

disp('(3) 对应齐次方程组的基础解系为:');
disp(x_null);

disp('因此，通解形式为: x = 特解 + k1*(基础解系列向量1) + k2*(基础解系列向量2) + ...');

% (4) 最小二乘解
x_data = [1.0, 1.5, 2.0, 2.5, 3.0, 3.5, 4.0, 4.5, 5.0];
y_data = [-1.4, 2.7, 3.0, 5.9, 8.4, 12.2, 16.6, 18.8, 26.2];
X = [ones(length(x_data), 1), x_data'.^2];
c4 = X \ y_data';
disp('(4) 最小二乘解 (y = c0 + c1*x^2):');
disp(c4);

% (5) 向量线性表示
beta = [2; -1; 3; 4];
a1 = [1; 2; -3; 1];
a2 = [5; -5; 12; 11];
a3 = [1; -3; 6; 3];

A5 = [a1, a2, a3];
Augmented5 = [A5, beta];

% 利用秩 (rank) 的充要条件来判断是否可以线性表示
rank_A5 = rank(A5);
rank_Aug = rank(Augmented5);

if rank_A5 == rank_Aug
    disp('(5) beta 可以由 a1, a2, a3 线性表示。');
    
    % 如果可以表示，计算具体的线性组合系数
    k = A5 \ beta;
    disp('线性组合系数 k 为:');
    disp(k);
else
    disp('(5) beta 不能由 a1, a2, a3 线性表示。');
end

